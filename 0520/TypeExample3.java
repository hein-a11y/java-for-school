public class TypeExample3 {
    
     public static void main(String[] args){
        int i = 9;
        int d = 2;
        double c = (double)i / (double)d;
        System.out.println("cの値は" + c);
        System.out.println("iの値は" + i);
        System.out.println("dの値は" + d);

        double a2 = 5;
        double b2 = 2;
        double c2 = a2 / b2;
        System.out.println("c2の値は" + c2);
     }
}
